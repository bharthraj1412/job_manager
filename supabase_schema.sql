-- Get job statistics for the current user
CREATE OR REPLACE FUNCTION get_job_stats()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  result jsonb;
BEGIN
  SELECT jsonb_build_object(
    'total',      COUNT(*),
    'bookmarked', COUNT(*) FILTER (WHERE status = 'Bookmarked'),
    'applied',    COUNT(*) FILTER (WHERE status = 'Applied'),
    'interview',  COUNT(*) FILTER (WHERE status = 'Interview'),
    'offer',      COUNT(*) FILTER (WHERE status = 'Offer'),
    'rejected',   COUNT(*) FILTER (WHERE status = 'Rejected'),
    'withdrawn',  COUNT(*) FILTER (WHERE status = 'Withdrawn'),
    'overdue',    COUNT(*) FILTER (WHERE deadline < CURRENT_DATE::text AND status NOT IN ('Rejected','Withdrawn','Offer')),
    'auto_applied', COUNT(*) FILTER (WHERE auto_applied = true),
    'high_priority', COUNT(*) FILTER (WHERE priority = 'High' AND status NOT IN ('Rejected','Withdrawn'))
  ) INTO result
  FROM jobs
  WHERE user_id = auth.uid();
  RETURN result;
END;
$$;

-- Full-text search on jobs
CREATE OR REPLACE FUNCTION search_jobs(query text)
RETURNS SETOF jobs LANGUAGE plpgsql SECURITY DEFINER AS $$
BEGIN
  RETURN QUERY
    SELECT * FROM jobs
    WHERE user_id = auth.uid()
      AND to_tsvector('english', coalesce(title,'') || ' ' || coalesce(company,'') || ' ' || coalesce(skills,''))
          @@ plainto_tsquery('english', query)
    ORDER BY created_at DESC;
END;
$$;

-- Upsert profile (creates if not exists)
CREATE OR REPLACE FUNCTION upsert_profile(profile_data jsonb)
RETURNS profiles LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  result profiles;
BEGIN
  INSERT INTO profiles (id, updated_at)
  VALUES (auth.uid(), timezone('utc', now()))
  ON CONFLICT (id) DO NOTHING;

  UPDATE profiles
  SET
    full_name        = COALESCE((profile_data->>'full_name'), full_name),
    email            = COALESCE((profile_data->>'email'), email),
    phone            = COALESCE((profile_data->>'phone'), phone),
    location         = COALESCE((profile_data->>'location'), location),
    headline         = COALESCE((profile_data->>'headline'), headline),
    summary          = COALESCE((profile_data->>'summary'), summary),
    skills           = COALESCE((profile_data->>'skills'), skills),
    experience       = COALESCE((profile_data->>'experience'), experience),
    education        = COALESCE((profile_data->>'education'), education),
    certifications   = COALESCE((profile_data->>'certifications'), certifications),
    languages        = COALESCE((profile_data->>'languages'), languages),
    linkedin         = COALESCE((profile_data->>'linkedin'), linkedin),
    github           = COALESCE((profile_data->>'github'), github),
    portfolio        = COALESCE((profile_data->>'portfolio'), portfolio),
    target_roles     = COALESCE((profile_data->>'target_roles'), target_roles),
    target_locations = COALESCE((profile_data->>'target_locations'), target_locations),
    expected_salary  = COALESCE((profile_data->>'expected_salary'), expected_salary),
    resume_template  = COALESCE((profile_data->>'resume_template'), resume_template),
    updated_at       = timezone('utc', now())
  WHERE id = auth.uid()
  RETURNING * INTO result;

  RETURN result;
END;
$$;

