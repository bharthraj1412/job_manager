-- User dashboard view (joins jobs + profile stats)
CREATE OR REPLACE VIEW user_job_summary AS
SELECT
  j.user_id,
  COUNT(*)                                              AS total_jobs,
  COUNT(*) FILTER (WHERE j.status = 'Applied')          AS applied,
  COUNT(*) FILTER (WHERE j.status = 'Interview')        AS interviews,
  COUNT(*) FILTER (WHERE j.status = 'Offer')            AS offers,
  COUNT(*) FILTER (WHERE j.status = 'Rejected')         AS rejected,
  COUNT(*) FILTER (WHERE j.auto_applied = true)         AS auto_applied,
  COUNT(*) FILTER (WHERE j.deadline < CURRENT_DATE::text
    AND j.status NOT IN ('Rejected','Withdrawn','Offer')) AS overdue,
  MAX(j.created_at)                                     AS last_added
FROM jobs j
GROUP BY j.user_id;

-- Upcoming deadlines view
CREATE OR REPLACE VIEW upcoming_deadlines AS
SELECT
  j.*,
  (j.deadline::date - CURRENT_DATE) AS days_remaining
FROM jobs j
WHERE j.deadline IS NOT NULL
  AND j.deadline >= CURRENT_DATE::text
  AND j.deadline <= (CURRENT_DATE + INTERVAL '14 days')::text
  AND j.status NOT IN ('Rejected','Withdrawn','Offer')
ORDER BY j.deadline ASC;

