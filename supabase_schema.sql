-- ─── 1. JOBS TABLE ────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS jobs (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at    timestamptz DEFAULT timezone('utc', now()) NOT NULL,
  updated_at    timestamptz DEFAULT timezone('utc', now()),
  user_id       uuid REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,

  -- Core fields
  title         text NOT NULL,
  company       text NOT NULL,
  location      text,
  type          text DEFAULT 'Full-time'
                  CHECK (type IN ('Full-time','Part-time','Internship','Contract','Freelance')),
  salary        text,
  skills        text,
  source        text,
  applylink     text,

  -- Status & tracking
  status        text DEFAULT 'Bookmarked'
                  CHECK (status IN ('Bookmarked','Applied','Interview','Offer','Rejected','Withdrawn')),
  priority      text DEFAULT 'Medium'
                  CHECK (priority IN ('High','Medium','Low')),
  applieddate   text,
  deadline      text,
  notes         text,

  -- Auto-apply tracking
  auto_applied  boolean DEFAULT false,
  auto_applied_at timestamptz,
  auto_apply_method text,   -- 'email' | 'link'

  -- Match score (calculated client-side, stored for sorting)
  match_score   smallint DEFAULT 0 CHECK (match_score >= 0 AND match_score <= 100)
);

