  is_pinned   boolean DEFAULT false
);

-- ─── 6. CALENDAR EVENTS TABLE ────────────────────────────────────────────────
-- Stores custom calendar events (reminders, follow-ups, phone screens, etc.)
-- Job-derived events (deadlines, applied dates) are computed client-side from
-- the jobs table, so they don't need to be stored here.
CREATE TABLE IF NOT EXISTS calendar_events (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at  timestamptz DEFAULT timezone('utc', now()) NOT NULL,
  user_id     uuid REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,

  -- Optional link back to a specific job
  job_id      bigint REFERENCES jobs(id) ON DELETE SET NULL,

  -- Event data
  title       text NOT NULL,
  event_date  date NOT NULL,
  event_time  text,                         -- e.g. "14:30" (stored as text, displayed as-is)
  type        text DEFAULT 'reminder'
                CHECK (type IN ('deadline','interview','follow_up','reminder','offer','other')),
  notes       text,
  is_done     boolean DEFAULT false NOT NULL
);

